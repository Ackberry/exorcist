import chalk from "chalk";
import type { HauntingReport, PackageHaunting, Severity } from "./types.js";
import { neutralizeMarkers, oneLineUntrusted } from "./untrusted.js";
import { readOwnVersion } from "./version.js";

export function renderMarkdown(report: HauntingReport): string {
  const haunted = report.hauntings.length;
  const quiet = report.quiet.length;
  const lines: string[] = [
    "# Exorcist haunting report",
    "",
    `- Target: \`${showLine(report.target, 1_024)}\``,
    `- Scanned: \`${showLine(report.scannedAt, 64)}\``,
    `- Installed packages: ${report.packageCount}`,
    `- Haunted: ${haunted}`,
    `- Quiet: ${quiet}`,
    `- Oracle: ${showLine(report.oracle.message)}`,
    ...(report.registryNote ? [`- Registry: ${showLine(report.registryNote)}`] : []),
    "",
    "## Packages",
    "",
    "| Package | Score | Exorcism | Where |",
    "| --- | --- | --- | --- |",
  ];

  for (const haunting of report.hauntings) {
    lines.push(
      `| ${cell(label(haunting.name, haunting.version))} | ${haunting.hauntingScore} | ${haunting.exorcism} | ${cell(place(haunting.direct, haunting.dev))} |`,
    );
  }
  for (const pkg of report.quiet) {
    lines.push(
      `| ${cell(label(pkg.name, pkg.version))} | 0 | — | ${cell(place(pkg.direct, pkg.dev))} |`,
    );
  }

  lines.push(
    "",
    "## Rules",
    "",
    "| Rule | Status | Findings | What it looks for |",
    "| --- | --- | --- | --- |",
  );
  for (const rule of report.rules) {
    lines.push(`| ${rule.kind} | ${rule.status} | ${rule.findings} | ${cell(rule.description)} |`);
  }

  if (report.hauntings.length === 0) {
    lines.push("", "The house is quiet. No rule flagged an installed package.", "");
  }

  for (const haunting of report.hauntings) {
    lines.push(
      "",
      `## ${label(haunting.name, haunting.version)}`,
      "",
      `- Path: ${haunting.path ? `\`${showLine(haunting.path, 1_024)}\`` : "_not on disk_"}`,
      `- Dependency: ${place(haunting.direct, haunting.dev)}`,
      `- Haunting score: **${haunting.hauntingScore}/100**`,
      `- Exorcism: **${haunting.exorcism}** — ${showLine(haunting.exorcismReason)}`,
      "",
      "### Findings",
      "",
    );
    for (const finding of haunting.findings) {
      lines.push(`#### ${showLine(finding.title)}`, "");
      lines.push(`- Rule: ${finding.rule}`);
      lines.push(`- Severity: ${finding.severity}`);
      lines.push(`- ${showLine(finding.detail)}`);
      if (finding.evidence) {
        const where = finding.evidencePath ? ` (\`${finding.evidencePath}\`)` : "";
        lines.push("", `Evidence${where}:`, "", fence(finding.evidence), "");
      } else {
        lines.push("");
      }
    }
    lines.push("### Oracle", "");
    if (haunting.judgment) {
      const impostor = impostorLine(haunting.judgment);
      if (impostor) {
        lines.push(`- Oracle: **${impostor}**`);
      } else {
        lines.push(`- Verdict: **${haunting.judgment.verdict}**`);
        lines.push(`- Confidence: ${haunting.judgment.confidence.toFixed(2)}`);
      }
      lines.push(`- Model score: ${haunting.judgment.score}`);
      lines.push(`- Summary: ${showLine(haunting.judgment.summary)}`);
      lines.push(`- Explanation: ${showLine(haunting.judgment.explanation)}`);
    } else if (haunting.oracleNote) {
      lines.push(`The oracle could not judge this package: ${showLine(haunting.oracleNote)}`);
    } else {
      lines.push("Not consulted for this package.");
    }
  }

  if (report.quiet.length > 0) {
    lines.push("", "## Quiet", "");
    for (const pkg of report.quiet) {
      lines.push(`- \`${label(pkg.name, pkg.version)}\` (${place(pkg.direct, pkg.dev)})`);
    }
  }

  lines.push(
    "",
    "---",
    "",
    `Generated by Exorcist ${readOwnVersion()}. Rule findings are local and static. Gemma is consulted only for packages a rule already flagged, and only when Ollama is running. Gemma's score cannot go below the rule total. Exorcist does not execute the packages it scans.`,
    "",
  );

  return lines.join("\n");
}

export function renderTerminal(report: HauntingReport): string {
  const version = readOwnVersion();
  const lines: string[] = [
    chalk.bold.magenta(`EXORCIST ${version}`),
    chalk.dim("a lockfile, a candle, and a local model"),
    "",
    `${chalk.dim("target")}    ${showLine(report.target, 1_024)}`,
    `${chalk.dim("scanned")}   ${showLine(report.scannedAt, 64)}`,
    `${chalk.dim("packages")}  ${report.packageCount} installed · ${report.hauntings.length} haunted · ${report.quiet.length} quiet`,
    `${chalk.dim("oracle")}    ${paintOracle(report.oracle.available, showLine(report.oracle.message))}`,
    ...(report.registryNote
      ? [`${chalk.dim("registry")}  ${chalk.yellow(showLine(report.registryNote, 96))}`]
      : []),
    "",
    chalk.dim("  rule           status   findings"),
  ];

  for (const rule of report.rules) {
    const status = rule.status === "stub" ? chalk.dim("stub  ") : chalk.green("active");
    lines.push(`  ${pad(rule.kind, 14)} ${status}   ${rule.findings}`);
  }

  if (report.hauntings.length === 0) {
    lines.push("", chalk.green("The house is quiet. No rule flagged an installed package."));
  }

  for (const haunting of report.hauntings) {
    lines.push("", chalk.bold(label(haunting.name, haunting.version)));
    lines.push(
      `  ${scoreBar(haunting.hauntingScore)}  ${paintExorcism(haunting.exorcism)}  ${chalk.dim(place(haunting.direct, haunting.dev))}`,
    );
    for (const finding of haunting.findings) {
      lines.push(`  ${paintSeverity(finding.severity)}  ${showLine(finding.title)}`);
      const snippet = oneLine(finding.evidence ?? finding.detail);
      const where = finding.evidencePath ? `${finding.evidencePath}: ` : "";
      lines.push(chalk.dim(`             ${where}${snippet}`));
    }
    if (haunting.judgment) {
      const impostor = impostorLine(haunting.judgment);
      if (impostor) {
        lines.push(`  ${chalk.dim("oracle")}    ${chalk.yellow(impostor)}`);
      } else {
        lines.push(
          `  ${chalk.dim("oracle")}    ${paintVerdict(haunting.judgment.verdict)} ${chalk.dim(`${haunting.judgment.confidence.toFixed(2)}  score ${haunting.judgment.score}`)}`,
        );
      }
      lines.push(chalk.dim(`             ${oneLine(haunting.judgment.summary, 96)}`));
    } else if (haunting.oracleNote) {
      lines.push(`  ${chalk.dim("oracle")}    ${chalk.yellow(oneLine(haunting.oracleNote, 96))}`);
    }
    lines.push(
      chalk.dim(`  exorcism  ${haunting.exorcism} — ${showLine(haunting.exorcismReason)}`),
    );
  }

  if (report.quiet.length > 0 && report.packageCount <= 15) {
    lines.push("", chalk.dim("quiet"));
    for (const pkg of report.quiet) {
      lines.push(chalk.dim(`  ${label(pkg.name, pkg.version)}`));
    }
  }

  return lines.join("\n");
}

export function printTerminal(report: HauntingReport): void {
  console.log(renderTerminal(report));
}

function impostorLine(judgment: NonNullable<PackageHaunting["judgment"]>): string | null {
  if (judgment.impersonating === undefined || !judgment.impersonationOf) return null;
  const word = judgment.impersonating ? "impostor of" : "not an impostor of";
  return `${word} ${showLine(judgment.impersonationOf)} (${judgment.confidence.toFixed(2)})`;
}

function label(name: string, version: string): string {
  return `${showLine(name, 214)}@${showLine(version, 64)}`;
}

function place(direct: boolean, dev: boolean): string {
  const kind = direct ? "direct" : "transitive";
  return dev ? `${kind}, dev` : kind;
}

function showLine(value: string, max = 2_000): string {
  return oneLineUntrusted(value, max).replaceAll("`", "'");
}

function cell(value: string): string {
  return showLine(value).replaceAll("|", "\\|");
}

function fence(code: string): string {
  return `\`\`\`\n${neutralizeMarkers(code).replaceAll("```", "'''")}\n\`\`\``;
}

function pad(value: string, width: number): string {
  return value.length >= width ? value : value + " ".repeat(width - value.length);
}

function oneLine(value: string, max = 88): string {
  return showLine(value, max);
}

function scoreBar(score: number): string {
  const filled = Math.round(score / 10);
  const bar = `${"█".repeat(filled)}${"░".repeat(10 - filled)}`;
  return `${paintScore(score, bar)}  ${paintScore(score, String(score).padStart(3, " "))}/100`;
}

function paintScore(score: number, text: string): string {
  if (score >= 75) return chalk.red(text);
  if (score >= 40) return chalk.yellow(text);
  return chalk.green(text);
}

function paintSeverity(severity: Severity): string {
  const labelText = pad(severity, 10);
  if (severity === "critical") return chalk.red.bold(labelText);
  if (severity === "high") return chalk.red(labelText);
  if (severity === "medium") return chalk.yellow(labelText);
  return chalk.dim(labelText);
}

function paintExorcism(exorcism: PackageHaunting["exorcism"]): string {
  if (exorcism === "remove") return chalk.red(exorcism);
  if (exorcism === "swap") return chalk.yellow(exorcism);
  return chalk.bold(exorcism);
}

function paintVerdict(verdict: NonNullable<PackageHaunting["judgment"]>["verdict"]): string {
  if (verdict === "malicious") return chalk.red(verdict);
  if (verdict === "suspicious") return chalk.yellow(verdict);
  return chalk.green(verdict);
}

function paintOracle(available: boolean, message: string): string {
  return available ? chalk.green(message) : chalk.yellow(message);
}
